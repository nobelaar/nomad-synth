"""Extract numpy's ziggurat tables (ki/wi/fi_double, from ziggurat_constants.h)
out of the installed numpy binary and write them as a Rust source file.

The tables are not reproducible bit for bit from the textbook recurrence, so the
exact values are located in numpy's compiled _generator module by searching for
a 256-entry run that matches the recurrence to 1e-6, then emitted as raw bits.

Usage: python tools/extract_ziggurat.py rust/nomad-core/src/ziggurat.rs
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np
import numpy.random

def approx_tables():
    m1 = 2.0**52
    dn = tn = 3.6541528853610088
    vn = 0.00492867323399
    q = vn / math.exp(-0.5 * dn * dn)
    ki, wi, fi = [0.0] * 256, [0.0] * 256, [0.0] * 256
    ki[0], wi[0], wi[255] = (dn / q) * m1, q / m1, dn / m1
    fi[0], fi[255] = 1.0, math.exp(-0.5 * dn * dn)
    for i in range(254, 0, -1):
        dn = math.sqrt(-2.0 * math.log(vn / dn + math.exp(-0.5 * dn * dn)))
        ki[i + 1] = (dn / tn) * m1
        tn = dn
        fi[i] = math.exp(-0.5 * dn * dn)
        wi[i] = dn / m1
    return {"ki": (ki, "<u8"), "wi": (wi, "<f8"), "fi": (fi, "<f8")}


def locate(raw: bytes, approx, dtype, rel=1e-6):
    ref = np.array(approx, dtype=np.float64)
    mask = ref != 0
    for off in range(8):
        a = np.frombuffer(raw[off: off + (len(raw) - off) // 8 * 8], dtype=dtype).astype(np.float64)
        with np.errstate(invalid="ignore"):
            cand = np.flatnonzero(np.abs(a - ref[10]) <= rel * abs(ref[10]))
        for c in cand:
            s = c - 10
            if s >= 0 and s + 256 <= a.size:
                seg = a[s:s + 256]
                if np.all(np.abs(seg[mask] - ref[mask]) <= rel * np.abs(ref[mask])):
                    return np.frombuffer(raw[off + s * 8: off + s * 8 + 256 * 8], dtype=dtype)
    raise SystemExit("table not found")


def main(out: Path) -> None:
    so = next(Path(numpy.random.__file__).parent.glob("_generator*.so"))
    raw = so.read_bytes()
    lines = [
        "//! numpy's ziggurat tables (`ziggurat_constants.h`, BSD-3-Clause), as raw bits.",
        f"//! Generated by tools/extract_ziggurat.py from numpy {np.__version__}; do not edit.",
        "",
    ]
    for name, (approx, dtype) in approx_tables().items():
        vals = locate(raw, approx, dtype)
        bits = vals.view("<u8")
        if name == "ki":
            lines.append("pub const KI: [u64; 256] = [")
        else:
            lines.append(f"pub const {name.upper()}_BITS: [u64; 256] = [")
        lines += [f"    {int(b):#018x}," for b in bits]
        lines.append("];")
        lines.append("")
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
